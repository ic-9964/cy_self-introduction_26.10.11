import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}) });
const base = process.env.CHECK_PAGE_URL || 'http://127.0.0.1:8080/?view=coastal#about';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('coastal-bubbles canvas').count(), 1);
  assert.equal(await page.locator('coastal-bubbles').evaluate(el => getComputedStyle(el).pointerEvents), 'none');
  assert.equal(await page.locator('coastal-bubbles').evaluate(el => el.frame), 0);
  await page.mouse.move(900, 760);
  await page.mouse.move(1350, 760, { steps: 40 });
  const trail = await page.locator('coastal-bubbles').evaluate(el => el.particles.map(p => ({ x: p.x, y: p.y })));
  assert(trail.length > 20, 'Moving across the scene must emit a visible trail');
  assert(Math.max(...trail.map(p => p.x)) - Math.min(...trail.map(p => p.x)) > 350, 'Bubbles must follow the path');
  assert(trail.every(p => Math.abs(p.y - 760) < 10), 'Bubbles must originate at the pointer');
  await page.waitForTimeout(2350);
  assert(await page.locator('coastal-bubbles').evaluate(el => el.particles.length === 0 && el.frame === 0), 'A stationary pointer must leave no bubbles or running frames');
  await page.locator('nav a[href="#projects"]').click();
  assert.equal(await page.locator('main > section:visible').getAttribute('id'), 'projects', 'Overlay must not block navigation');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.mouse.move(400, 400, { steps: 10 });
  await page.waitForTimeout(100);
  assert(await page.locator('coastal-bubbles').evaluate(el => el.particles.length === 0 && el.frame === 0 && getComputedStyle(el).display === 'none'));
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.mouse.move(900, 760, { steps: 8 });
  await page.waitForTimeout(80);
  assert(await page.locator('coastal-bubbles').evaluate(el => el.particles.length > 0));
  await page.setViewportSize({ width: 830, height: 612 });
  await page.waitForTimeout(80);
  assert(await page.locator('coastal-bubbles').evaluate(el => el.width === document.documentElement.clientWidth && el.height === innerHeight));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('coastal-bubbles').evaluate(el => { window.removedBubbles = el; el.remove(); });
  await page.mouse.move(100, 100, { steps: 8 });
  assert(await page.evaluate(() => window.removedBubbles.frame === 0 && window.removedBubbles.abort.signal.aborted && window.removedBubbles.particles.length === 0));
  await page.evaluate(() => document.body.append(window.removedBubbles));
  assert.equal(await page.locator('coastal-bubbles canvas').count(), 1);
  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await touch.goto(base, { waitUntil: 'networkidle' });
  await touch.touchscreen.tap(180, 400);
  assert(await touch.locator('coastal-bubbles').evaluate(el => el.particles.length === 0 && el.frame === 0 && getComputedStyle(el).display === 'none'));
  assert.deepEqual(errors, []);
  console.log('PASS: pointer trail, automatic disappearance/idle, click-through navigation, reduced motion, resize/no overflow, cleanup/reconnect, touch disabled.');
} finally { await browser.close(); }
